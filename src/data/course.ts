const WORDS_PER_LESSON = 6
const SENTENCES_PER_LESSON = 2

function buildUnit(seed: UnitSeed): Unit {
  const words: Word[] = seed.words.map((raw, index) => {
    const [tt, latin, ru, pos, emoji, confidence = 'high', note] = raw
    return {
      id: `u${seed.id}-w${String(index + 1).padStart(2, '0')}`,
      tt,
      latin,
      ru,
      pos,
      unit: seed.id,
      lesson: Math.min(4, Math.floor(index / WORDS_PER_LESSON) + 1),
      emoji,
      confidence,
      note,
    }
  })

  const sentences: Sentence[] = seed.sentences.map((raw, index) => {
    const [tt, ru] = raw
    return {
      id: `u${seed.id}-s${String(index + 1).padStart(2, '0')}`,
      tt,
      ru,
      unit: seed.id,
      lesson: Math.min(4, Math.floor(index / SENTENCES_PER_LESSON) + 1),
    }
  })

  return { ...seed, words, sentences }
}

