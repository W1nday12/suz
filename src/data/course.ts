export const units: Unit[] = [u1, u2, u3, u4, u5, u6, u7, u8, u9, u10, u11, u12].map(buildUnit)

export const allWords: Word[] = units.flatMap((unit) => unit.words)
export const allSentences: Sentence[] = units.flatMap((unit) => unit.sentences)

export const wordById = new Map(allWords.map((word) => [word.id, word]))
export const sentenceById = new Map(allSentences.map((sentence) => [sentence.id, sentence]))
export const unitById = new Map(units.map((unit) => [unit.id, unit]))

export function getUnit(unitId: number): Unit {
  const unit = unitById.get(unitId)
  if (!unit) throw new Error(`Unknown unit ${unitId}`)
  return unit
}

export function getLessonWords(unitId: number, lesson: number): Word[] {
  const unit = getUnit(unitId)
  if (lesson === 0) return unit.words
  return unit.words.filter((word) => word.lesson === lesson)
}

export function getLessonSentences(unitId: number, lesson: number): Sentence[] {
  const unit = getUnit(unitId)
  if (lesson === 0) return unit.sentences
  return unit.sentences.filter((sentence) => sentence.lesson === lesson)
}

export function getGrammar(unitId: number): GrammarCard[] {
  return getUnit(unitId).grammar
}

export const courseStats = {
  units: units.length,
  words: allWords.length,
  sentences: allSentences.length,
  lessons: units.length * 5,
}

export function findExampleForWord(word: Word): Sentence | undefined {
  const stem = word.tt.split(' ')[0].replace(/[.!?,;:]+$/g, '')
  return allSentences.find((sentence) => sentence.unit === word.unit && sentence.tt.includes(stem))
}
